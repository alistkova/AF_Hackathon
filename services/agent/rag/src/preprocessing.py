SUFFIX_RE = re.compile(r"\s+(ао|ап|адр|пао|оао)$|(адр)$", re.IGNORECASE)
FX_RE = re.compile(r"^(Brent|WTI|Si|RI|USDRUB|EURRUB|CNYRUB|BZ|CL)\b", re.IGNORECASE)
INDEX_RE = re.compile(r"^(Индекс|IMOEX|RTS|MOEX|Nasdaq|S&P)", re.IGNORECASE)

def normalize_tag(tag):
    return SUFFIX_RE.sub("", tag.strip()).strip()

def tag_to_section(tag):
    t = normalize_tag(tag)
    if not t: return None
    if FX_RE.match(t) or INDEX_RE.match(t): return None
    if t in COMPANY_TO_SECTION: return COMPANY_TO_SECTION[t]
    for comp, sec in COMPANY_TO_SECTION.items():
        if comp.lower() in t.lower() or t.lower() in comp.lower():
            return sec
    tl = t.lower()
    for sec, kws in SECTIONS.items():
        if any(kw.lower() in tl for kw in kws):
            return sec
    return None

SECTION_PATTERNS = {
    sec: re.compile(r"(" + "|".join(re.escape(kw) for kw in kws) + r")", re.IGNORECASE)
    for sec, kws in SECTIONS.items()
}

def _safe_str(x):
    if x is None or pd.isna(x): return ""
    return str(x)

def classify_by_text(title, body, min_hits=1):
    text = _safe_str(title) + " " + _safe_str(body)[:2000]
    if not text.strip(): return []
    scores = {}
    for sec, pat in SECTION_PATTERNS.items():
        hits = len(pat.findall(text))
        if hits >= min_hits:
            scores[sec] = hits
    return [s for s, _ in sorted(scores.items(), key=lambda x: -x[1])[:3]]

def full_section_list(row):
    secs = set()
    for t in row["tags_list"]:
        if t is None or pd.isna(t): continue
        s = tag_to_section(str(t))
        if s: secs.add(s)
    if not secs:
        secs = set(classify_by_text(row["title"], row["body"]))
    if not secs and row["source"] in ("smart_lab", "t_analytic"):
        secs = {"макро"}
    return sorted(secs)

df["sections"] = df.apply(full_section_list, axis=1)

